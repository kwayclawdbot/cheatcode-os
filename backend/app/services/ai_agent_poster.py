async def run_scheduled_post_job_async(max_posts: int = 1) -> dict:
    """Async shim for APScheduler (runs the sync implementation in a thread
    so blocking supabase / claude CLI calls don't stall the event loop)."""
    import asyncio
    return await asyncio.to_thread(run_scheduled_post_job, max_posts)


def run_scheduled_post_job(max_posts: int = 1) -> dict:
    """Called by APScheduler every ~20 min during the day.

    Returns a small status dict for logs/telemetry.
    """
    status = {"enabled": False, "spend_ok": False, "agent": None, "post_id": None, "reason": None}

    if not is_agent_posting_enabled():
        status["reason"] = "disabled"
        return status
    status["enabled"] = True

    spend = _global_agent_spend_today_usd()
    if spend >= AGENT_DAILY_SPEND_CAP_USD:
        status["reason"] = f"daily cap hit (${spend:.2f}/${AGENT_DAILY_SPEND_CAP_USD})"
        log.warning("agent_poster: daily spend cap hit %.2f", spend)
        return status
    status["spend_ok"] = True

    agents = _get_active_agents()
    if not agents:
        status["reason"] = "no active agents"
        return status

    for _ in range(max_posts):
        agent = _pick_next_agent(agents)
        if not agent:
            break
        status["agent"] = agent.handle

        content = generate_post_content(agent)
        if not content:
            status["reason"] = "generation failed"
            continue

        post_id = post_as_agent(agent, content)
        if post_id:
            status["post_id"] = post_id
            # Remove this agent from candidates for subsequent iterations
            agents = [a for a in agents if a.id != agent.id]

    return status


