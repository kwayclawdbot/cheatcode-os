REPLY_COMPAT = {
    # bearish/contrarian responds to bullish swing/day/mega
    "contrarian": ["swing", "day", "meme", "newbie", "ta"],
    "risk":       ["day", "options", "swing", "meme"],
    "macro":      ["swing", "value", "contrarian"],
    "newbie":     ["day", "swing", "options", "macro", "ta", "value", "recap"],
    "ta":         ["swing", "day"],
    "value":      ["contrarian", "swing"],
}


def _pick_replier(agents: list[AgentRow], parent_author_style: str) -> AgentRow | None:
    pool = [a for a in agents if a.style != parent_author_style]
    if not pool:
        return None
    # Prefer explicitly compatible responders
    preferred = [
        a for a in pool
        if parent_author_style in REPLY_COMPAT.get(a.style, [])
    ]
    if preferred:
        return random.choice(preferred)
    return random.choice(pool)


def generate_reply_for_post(parent_post: dict) -> str | None:
    """30% chance, called after a new agent post is inserted."""
    if random.random() > 0.30:
        return None

    if not is_agent_posting_enabled():
        return None

    agents = _get_active_agents()
    if not agents:
        return None

    # Find the parent author's agent style
    parent_user = parent_post.get("user_id")
    author = next((a for a in agents if a.profile_id == parent_user), None)
    parent_style = author.style if author else "swing"

    replier = _pick_replier(agents, parent_style)
    if not replier:
        return None

    parent_body = (parent_post.get("body") or "")[:400]
    parent_ticker = parent_post.get("ticker") or ""
    system = replier.voice_prompt + COMPLIANCE_FOOTER + HUMANIZER_RULES
    ticker_instruction = ""
    if parent_ticker:
        ticker_instruction = (
            f"IMPORTANT: Reference ${parent_ticker} by its cashtag naturally in your reply "
            f"so readers know which stock you're talking about. "
        )
    user = (
        f"Another trader just posted this:\n"
        f"---\n{parent_body}\n---\n"
        f"Ticker: {parent_ticker or '-'}\n\n"
        f"Write a SHORT reply (1-2 sentences) in your voice. Do not agree reflexively — "
        f"if you disagree with the premise, say so directly but respectfully. "
        f"{ticker_instruction}"
        f"Your reply MUST sound like a real person typed it — no AI patterns. "
        f"Vary sentence length. Use casual language. Have an opinion. "
        f"Output JSON: {{\"body\": \"...\"}} and nothing else."
    )

    result = _invoke_claude_cli(system, user)
    if result is None:
        return None

    raw = result["text"]
    try:
        _record_agent_usage(
            replier.profile_id,
            model=result["model"],
            input_tokens=result["input_tokens"],
            output_tokens=result["output_tokens"],
            cost_usd=result["cost_usd"],
        )
    except Exception:
        pass

    parsed = _parse_post_json(raw)
    if not parsed or not parsed.get("body"):
        return None

    body = str(parsed["body"]).strip()
    if len(body) < 5:
        return None
    if len(body) > 400:
        body = body[:400].rsplit(" ", 1)[0] + "…"

    # Insert as comment
    db = get_supabase()
    post_id = parent_post.get("id")
    try:
        db.table("post_comments").insert({
            "post_id": post_id,
            "user_id": replier.profile_id,
            "body": body,
        }).execute()
        # Bump comments_count via SQL increment (avoids stale counter race).
        # supabase-py doesn't support raw increments, so RPC or re-count.
        count_res = (
            db.table("post_comments")
            .select("id", count="exact")
            .eq("post_id", post_id)
            .execute()
        )
        db.table("feed_posts").update({
            "comments_count": count_res.count or 0,
        }).eq("id", post_id).execute()

        db.table("ai_agents").update({
            "last_reply_at": datetime.now(timezone.utc).isoformat(),
        }).eq("id", replier.id).execute()
    except Exception as e:
        log.warning("reply insert failed: %s", e)
        return None

    log.info("agent reply ok replier=%s parent=%s", replier.handle, parent_post.get("id"))
    return body


