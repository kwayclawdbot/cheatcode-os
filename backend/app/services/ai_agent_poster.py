@dataclass
class AgentRow:
    """Flat representation of an agent row joined with its profile."""
    id: str                    # ai_agents.id
    profile_id: str            # profiles.id (used as feed_posts.user_id)
    persona_name: str
    handle: str
    display_name: str
    specialty: str
    style: str
    voice_prompt: str
    specialty_tickers: list[str]
    cadence_per_day: int
    market_hours_weight: float
    last_post_at: datetime | None
    post_count: int


@dataclass
class PostContent:
    body: str
    post_type: str
    sentiment: str | None           # bullish / bearish / neutral / None
    ticker: str | None              # primary ticker mentioned, if any
    tags: list[str]


