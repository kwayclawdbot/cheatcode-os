# Claude Code CLI binary. Override via CLAUDE_CLI_BIN env var if not on PATH
# (e.g. ~/.local/bin/claude on macOS).
CLAUDE_CLI_BIN = os.environ.get("CLAUDE_CLI_BIN", "claude")

# Model alias passed to `claude -p --model`. "haiku" resolves to the latest
# Haiku — currently 4.5. Use "sonnet" for higher quality at higher cost.
AGENT_MODEL_ALIAS = os.environ.get("CC_AGENT_MODEL", "haiku")

# Subprocess timeout per generation call. Most Haiku responses come back in
# 3-6 seconds; 60s is a generous ceiling.
CLAUDE_CALL_TIMEOUT_SECONDS = 60

# Hard daily circuit breaker. NOTE: in CLI mode the recorded cost is the
# API-equivalent rate reported by `claude -p`, not what the user actually
# pays — Claude Code subscription is flat-rate, so real cost is $0.
# We still record the equivalent so usage is visible alongside Kai spend.
# A typical Haiku call with full Claude Code context loaded is ~$0.07
# equivalent, so $25/day comfortably handles ~350 posts before tripping.
AGENT_DAILY_SPEND_CAP_USD = 25.0

# Post-type distribution per agent style. Not all styles post the same
# kinds of things — Alex (day) mostly posts `market_take`, Samir (value)
