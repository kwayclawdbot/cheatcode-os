def _get_active_agents() -> list[AgentRow]:
    db = get_supabase()
    rows = (
        db.table("ai_agents")
        .select("*, profiles!ai_agents_profile_id_fkey(id, handle, display_name)")
        .eq("active", True)
        .execute()
    )
    out: list[AgentRow] = []
    for r in (rows.data or []):
        prof = r.get("profiles") or {}
        last = r.get("last_post_at")
        last_dt = None
        if last:
            try:
                last_dt = datetime.fromisoformat(last.replace("Z", "+00:00"))
            except Exception:
                last_dt = None
        out.append(AgentRow(
            id=r["id"],
            profile_id=r["profile_id"],
            persona_name=r.get("persona_name") or "",
            handle=prof.get("handle") or "",
            display_name=prof.get("display_name") or "",
            specialty=r.get("specialty") or "",
            style=r.get("style") or "",
            voice_prompt=r.get("voice_prompt") or "",
            specialty_tickers=list(r.get("specialty_tickers") or []),
            cadence_per_day=int(r.get("cadence_per_day") or 3),
            market_hours_weight=float(r.get("market_hours_weight") or 0.75),
            last_post_at=last_dt,
            post_count=int(r.get("post_count") or 0),
        ))
    return out


def _is_market_hours_now() -> bool:
    """Rough US RTH check in UTC (9:30-16:00 ET → 13:30-20:00 UTC standard,
    12:30-19:00 UTC DST). Not exact — good enough for weighting."""
    now = datetime.now(timezone.utc)
    if now.weekday() >= 5:
        return False
    hour = now.hour + now.minute / 60
    return 13.0 <= hour <= 20.5


def _agent_weight(agent: AgentRow, now: datetime) -> float:
    """Weighted selection score. Higher = more likely to post next."""
    # Base weight from cadence (posts/day)
    weight = float(agent.cadence_per_day)

    # Cool down if posted recently (avoid back-to-back same agent)
    if agent.last_post_at is not None:
        minutes_since = (now - agent.last_post_at).total_seconds() / 60.0
        # Minimum spacing: ~ (1440 / cadence) minutes, with a 20-min floor
        min_spacing = max(20.0, 1440.0 / max(agent.cadence_per_day, 1))
        if minutes_since < min_spacing:
            weight *= 0.05
        elif minutes_since < min_spacing * 2:
            weight *= 0.5

    # Market hours bias
    if _is_market_hours_now():
        weight *= 1.0 + agent.market_hours_weight
    else:
        weight *= max(0.1, 1.0 - agent.market_hours_weight)
        # EOD recap agent biases HEAVILY toward post-close
        if agent.style == "recap" and 20.0 <= (now.hour + now.minute / 60) <= 22.0:
            weight *= 5.0

    return max(weight, 0.001)


def _pick_next_agent(agents: list[AgentRow]) -> AgentRow | None:
    if not agents:
        return None
    now = datetime.now(timezone.utc)
    weights = [_agent_weight(a, now) for a in agents]
    total = sum(weights)
    if total <= 0:
        return random.choice(agents)
    return random.choices(agents, weights=weights, k=1)[0]


# ============================================================
# Market context
# ============================================================

def _fetch_market_context(agent: AgentRow) -> dict:
    """Gather fresh, grounded context for the post prompt.

    - Top movers from `tickers` filtered by agent's specialty_tickers
      (or top overall convergence_score if the agent is macro/risk/newbie)
    - Latest radar_snapshots sentiment summary
    - Recent agent posts (last 2h) so we don't repeat ourselves
    """
    db = get_supabase()
    ctx: dict[str, Any] = {}

    # Specialty-filtered ticker snapshot
    try:
        q = db.table("tickers").select(
            "symbol, name, sector, last_price, price_change_pct, convergence_score, direction, catalyst"
        )
        if agent.specialty_tickers:
            q = q.in_("symbol", agent.specialty_tickers)
            res = q.order("price_change_pct", desc=True).limit(8).execute()
        else:
            res = q.order("convergence_score", desc=True).limit(10).execute()
        ctx["tickers"] = res.data or []
    except Exception as e:
        log.warning("ticker fetch failed: %s", e)
        ctx["tickers"] = []

    # Latest radar sentiment
    try:
        res = (
            db.table("radar_snapshots")
            .select("market_sentiment, sentiment_summary, created_at")
            .order("created_at", desc=True)
            .limit(1)
            .execute()
        )
        if res.data:
            ctx["radar"] = res.data[0]
    except Exception as e:
        log.warning("radar fetch failed: %s", e)

    # Recent feed posts (so we don't repeat)
    try:
        two_hours_ago = (datetime.now(timezone.utc) - timedelta(hours=2)).isoformat()
        res = (
            db.table("feed_posts")
            .select("body, ticker, created_at")
            .gte("created_at", two_hours_ago)
            .order("created_at", desc=True)
            .limit(10)
            .execute()
        )
        ctx["recent_posts"] = res.data or []
    except Exception as e:
        log.warning("recent posts fetch failed: %s", e)
        ctx["recent_posts"] = []

    return ctx


# ============================================================
# Prompt building
# ============================================================

COMPLIANCE_FOOTER = (
    "\n\nHARD RULES (never break):\n"
    "1. Never give specific entry, target, or stop prices.\n"
    "2. Never tell anyone to buy, sell, short, or close.\n"
    "3. Never cite a price as a forecast.\n"
    "4. Frame everything as observation, education, or scenario analysis.\n"
    "5. Stay in character. You are an AI persona — do not claim real trades or P&L.\n"
    "6. Output JSON matching the schema you are given. Nothing else.\n"
)


def _pick_post_type(style: str) -> str:
    options = STYLE_POST_TYPES.get(style, [("market_take", 1.0)])
    types = [t for t, _ in options]
    weights = [w for _, w in options]
    return random.choices(types, weights=weights, k=1)[0]


def _build_user_prompt(agent: AgentRow, context: dict, post_type: str) -> str:
    lines = [
        f"Write one social post as {agent.persona_name}.",
        f"Post type: {post_type}",
        "",
        "=== CURRENT MARKET CONTEXT (use only facts from here, do not invent) ===",
    ]

    radar = context.get("radar")
    if radar:
        lines.append(f"Market sentiment: {radar.get('market_sentiment','unknown')}")
        summ = radar.get("sentiment_summary") or ""
        if summ:
            lines.append(f"Sentiment summary: {summ[:300]}")

    tickers = context.get("tickers") or []
    if tickers:
        lines.append("")
        lines.append("Tickers on your radar right now (symbol, name, change%, convergence, direction, catalyst):")
        for t in tickers[:8]:
            chg = t.get("price_change_pct")
            chg_s = f"{chg:+.2f}%" if isinstance(chg, (int, float)) else "n/a"
            lines.append(
                f"- {t.get('symbol')} ({t.get('name') or '?'}) {chg_s} "
                f"conv={t.get('convergence_score',0)} dir={t.get('direction') or '?'} "
                f"catalyst={(t.get('catalyst') or '')[:80]}"
            )

    recent = context.get("recent_posts") or []
    if recent:
        lines.append("")
        lines.append("Recent posts in the feed (DO NOT REPEAT these angles or tickers already covered):")
        for p in recent[:6]:
            body = (p.get("body") or "")[:120].replace("\n", " ")
            lines.append(f"- [{p.get('ticker') or '-'}] {body}")

    lines.extend([
        "",
        "=== OUTPUT SCHEMA ===",
        "Return a JSON object and nothing else:",
        "{",
        '  "body": "<the post text — follow your voice rules strictly>",',
        '  "sentiment": "bullish" | "bearish" | "neutral" | null,',
        '  "ticker": "<primary ticker mentioned, or null>",',
        '  "tags": ["tag1","tag2"]',
        "}",
        "",
        "Tags should be 0-3 lowercase single-word topics (e.g. vwap, earnings, macro, flow, breakout).",
        "If the post is a question or education piece, sentiment should usually be null.",
        "Do NOT wrap the JSON in markdown code fences.",
    ])
    return "\n".join(lines)


