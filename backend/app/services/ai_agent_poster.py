def post_as_agent(agent: AgentRow, content: PostContent) -> str | None:
    """Insert into feed_posts, bump agent stats. Returns new post id."""
    db = get_supabase()
    row = {
        "user_id": agent.profile_id,
        "post_type": content.post_type,
        "body": content.body,
        "sentiment": content.sentiment,
        "ticker": content.ticker,
        "tags": content.tags,
    }
    try:
        res = db.table("feed_posts").insert(row).execute()
    except Exception as e:
        log.error("feed_posts insert failed for agent %s: %s", agent.handle, e)
        return None

    post_id = None
    if res.data:
        post_id = res.data[0].get("id")

    try:
        db.table("ai_agents").update({
            "last_post_at": datetime.now(timezone.utc).isoformat(),
            "post_count": agent.post_count + 1,
        }).eq("id", agent.id).execute()
    except Exception as e:
        log.warning("ai_agents stat update failed for %s: %s", agent.handle, e)

    log.info("agent post ok handle=%s post_id=%s ticker=%s", agent.handle, post_id, content.ticker)
    return post_id


