def _parse_post_json(text: str) -> dict | None:
    """Tolerant parser — strips code fences, finds first {...} block."""
    if not text:
        return None
    text = text.strip()
    if text.startswith("```"):
        text = re.sub(r"^```(?:json)?\s*", "", text)
        text = re.sub(r"\s*```$", "", text)
    # First JSON object
    start = text.find("{")
    end = text.rfind("}")
    if start == -1 or end == -1:
        return None
    try:
        return json.loads(text[start:end + 1])
    except json.JSONDecodeError:
        return None


def generate_post_content(agent: AgentRow, dry_run: bool = False) -> PostContent | None:
    """Spawn `claude -p`, return parsed PostContent. Records usage in kai_usage."""
    context = _fetch_market_context(agent)
    post_type = _pick_post_type(agent.style)
    system = agent.voice_prompt + COMPLIANCE_FOOTER + HUMANIZER_RULES
    user = _build_user_prompt(agent, context, post_type)

    if dry_run:
        log.info("[dry_run] agent=%s post_type=%s", agent.handle, post_type)

    result = _invoke_claude_cli(system, user)
    if result is None:
        log.error("agent post generation failed (%s): claude CLI returned no result", agent.handle)
        return None

    raw = result["text"]

    # Record spend (cost comes from CLI, including cache reads/writes)
    try:
        _record_agent_usage(
            agent.profile_id,
            model=result["model"],
            input_tokens=result["input_tokens"],
            output_tokens=result["output_tokens"],
            cost_usd=result["cost_usd"],
        )
    except Exception as e:
        log.warning("usage recording failed for agent %s: %s", agent.handle, e)

    parsed = _parse_post_json(raw)
    if not parsed or not parsed.get("body"):
        log.warning("agent %s produced unparsable output: %r", agent.handle, raw[:200])
        return None

    body = str(parsed["body"]).strip()
    if len(body) < 10:
        log.warning("agent %s produced too-short body: %r", agent.handle, body)
        return None
    if len(body) > 600:
        body = body[:600].rsplit(" ", 1)[0] + "…"

    sentiment = parsed.get("sentiment")
    if sentiment not in ("bullish", "bearish", "neutral", None):
        sentiment = None

    ticker = parsed.get("ticker")
    if ticker:
        ticker = str(ticker).upper().strip()
        if not re.match(r"^[A-Z0-9.\-]{1,12}$", ticker):
            ticker = None

    # General commentary posts (questions, education, recaps, broad market takes
    # that don't focus on a specific symbol) should NOT be filed under a ticker
    # chat. Only trade_idea and chart_post types, or posts whose body clearly
    # revolves around the ticker, keep the ticker association.
    if ticker and post_type in ("question", "education", "recap"):
        ticker = None
    elif ticker and post_type == "market_take":
        # If the ticker symbol doesn't appear in the body as a cashtag or
        # standalone mention, it's likely a general take — clear the ticker.
        body_upper = body.upper()
        if f"${ticker}" not in body_upper and f" {ticker} " not in f" {body_upper} ":
            ticker = None

    tags = parsed.get("tags") or []
    if isinstance(tags, str):
        tags = [tags]
    tags = [str(t).lower().strip()[:20] for t in tags if t][:3]
    tags.append("ai_agent")  # makes filtering trivial

    return PostContent(
        body=body,
        post_type=POST_TYPE_NORMALIZATION.get(post_type, "take"),
        sentiment=sentiment,
        ticker=ticker,
        tags=tags,
    )


