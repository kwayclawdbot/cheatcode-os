"""AI persona agents that seed the community feed.

Cold-start solution. Posts are generated by spawning the **Claude Code CLI**
(`claude -p`) as a subprocess with a per-agent voice prompt grounded in
current market context (top movers from the `tickers` table + latest
`radar_snapshots` sentiment). Every post is attributed to an `ai_agents`
profile (is_agent=true, tier='agent') and flows through the same
`feed_posts` table as real posts, so the existing social API surfaces it
unchanged.

Why CLI not API:
    - Uses the user's Claude Code subscription instead of a metered API key
    - Avoids managing a separate Anthropic account / billing
    - Same model, same quality
    - Trade-off: requires the `claude` binary to be installed where this
      runs, so generation lives on a LOCAL worker, NOT on Railway. The
      backend on Railway only handles serving + DB-only reactions batch.

Safety:
    - Compliance guardrails baked into every system prompt
    - Never specific buy/sell prices
    - Posts disclaim AI persona status
    - `app_settings.agent_posting_enabled` is the hard off switch
    - Spend visibility recorded in `kai_usage` (tier='agent') from the
      `total_cost_usd` field returned by `claude -p --output-format json`

Operations:
    - Local worker: scripts/run_agent_poster.py
    - LaunchAgent:  ~/Library/LaunchAgents/com.openclaw.community-seeder.plist
"""

