def _load_setting(key: str, default: Any) -> Any:
    db = get_supabase()
    try:
        row = db.table("app_settings").select("value").eq("key", key).maybe_single().execute()
        if row is None or row.data is None:
            return default
        return row.data.get("value", default)
    except Exception as e:
        log.warning("app_settings read failed (%s): %s", key, e)
        return default


def is_agent_posting_enabled() -> bool:
    return bool(_load_setting("agent_posting_enabled", False))


def _global_agent_spend_today_usd() -> float:
    """Sum kai_usage.cost_usd for tier='agent' since start of UTC day."""
    db = get_supabase()
    day_start = datetime.now(timezone.utc).replace(hour=0, minute=0, second=0, microsecond=0)
    try:
        rows = (
            db.table("kai_usage")
            .select("cost_usd")
            .eq("tier", "agent")
            .gte("created_at", day_start.isoformat())
            .execute()
        )
        return sum(float(r.get("cost_usd") or 0) for r in (rows.data or []))
    except Exception as e:
        log.warning("agent spend query failed: %s", e)
        return 0.0


def _record_agent_usage(
    profile_id: str,
    model: str,
    input_tokens: int,
    output_tokens: int,
    cost_usd: float,
) -> float:
    """Persist a row to kai_usage so spend is visible alongside Kai usage.

    Cost comes straight from `claude -p --output-format json`'s
    `total_cost_usd` field — no need to estimate, the CLI gives us the
    real number including cache reads / cache writes.
    """
    db = get_supabase()
    try:
        db.table("kai_usage").insert({
            "user_id": profile_id,
            "conversation_id": None,
            "model": model,
            "input_tokens": input_tokens,
            "output_tokens": output_tokens,
            "cost_usd": cost_usd,
            "tier": "agent",
        }).execute()
    except Exception as e:
        log.error("failed to record agent usage: %s", e)
    return cost_usd


def _invoke_claude_cli(system_prompt: str, user_prompt: str) -> dict | None:
    """Run `claude -p` as a subprocess and return parsed result dict.

    Writes the system prompt to a temp file (avoids any arg-length / shell
    escaping issues with multi-line prompts) and uses
    `--append-system-prompt-file`. The user prompt is passed positionally.

    Returns a dict with keys: text (str), input_tokens, output_tokens,
    cost_usd, model. Returns None on failure.
    """
    # Write the system prompt to a temp file. Delete after the call.
    with tempfile.NamedTemporaryFile(
        mode="w", suffix=".txt", delete=False, encoding="utf-8"
    ) as f:
        f.write(system_prompt)
        system_prompt_path = f.name

    argv = [
        CLAUDE_CLI_BIN,
        "-p",
        "--model", AGENT_MODEL_ALIAS,
        "--output-format", "json",
        "--append-system-prompt-file", system_prompt_path,
        user_prompt,
    ]

    # Strip ANTHROPIC_API_KEY from the subprocess env. The backend's
    # Pydantic config requires it as a field, but Claude Code prefers an
    # env var over its OAuth keychain — so a stub value would short-circuit
    # the user's actual subscription. Remove it so the CLI falls back to
    # the keychain OAuth credential like a normal interactive session.
    sub_env = {k: v for k, v in os.environ.items() if k != "ANTHROPIC_API_KEY"}

    try:
        try:
            proc = subprocess.run(
                argv,
                capture_output=True,
                text=True,
                timeout=CLAUDE_CALL_TIMEOUT_SECONDS,
                env=sub_env,
            )
        except FileNotFoundError:
            log.error("claude CLI not found on PATH (CLAUDE_CLI_BIN=%s)", CLAUDE_CLI_BIN)
            return None
        except subprocess.TimeoutExpired:
            log.error("claude CLI timed out after %ds", CLAUDE_CALL_TIMEOUT_SECONDS)
            return None

        if proc.returncode != 0:
            log.error(
                "claude CLI exited %d  stderr=%r  stdout=%r",
                proc.returncode,
                (proc.stderr or "")[:500],
                (proc.stdout or "")[:500],
            )
            return None

        try:
            envelope = json.loads(proc.stdout)
        except json.JSONDecodeError as e:
            log.error("claude CLI output not valid JSON: %s — head=%r", e, proc.stdout[:300])
            return None
    finally:
        try:
            os.unlink(system_prompt_path)
        except OSError:
            pass

    if envelope.get("is_error"):
        log.error("claude CLI returned error envelope: %s", envelope.get("result", "")[:300])
        return None

    text = envelope.get("result") or ""
    usage = envelope.get("usage") or {}
    model_usage = envelope.get("modelUsage") or {}
    # Pick the first (and usually only) model in modelUsage for the model name
    model_name = next(iter(model_usage.keys()), AGENT_MODEL_ALIAS)

    return {
        "text": text,
        "input_tokens": int(usage.get("input_tokens") or 0),
        "output_tokens": int(usage.get("output_tokens") or 0),
        "cost_usd": float(envelope.get("total_cost_usd") or 0.0),
        "model": model_name,
    }


