"""AI persona agents that seed the community feed.

Cold-start solution. Posts are generated by Claude Haiku with a per-agent
voice prompt grounded in current market context (top movers from the
`tickers` table + latest `radar_snapshots` sentiment). Every post is
attributed to an `ai_agents` profile (is_agent=true, tier='agent') and
flows through the same `feed_posts` table as real posts, so the existing
social API surfaces it unchanged.

Safety:
    - Compliance guardrails baked into every system prompt
    - Never specific buy/sell prices
    - Posts disclaim AI persona status
    - `app_settings.agent_posting_enabled` is the hard off switch
    - Global daily spend cap shared with Kai via `kai_usage` table

Scheduling is wired in `main.py` — see `run_scheduled_post_job()`.
"""

from __future__ import annotations

import json
import logging
import random
import re
from dataclasses import dataclass
from datetime import datetime, timezone, timedelta
from typing import Any

import anthropic

from app.core.config import get_settings
from app.core.supabase import get_supabase
from app.services.kai_budget import estimate_cost_usd

log = logging.getLogger("ai_agent_poster")

# Model choice: Haiku 4.5 is cheap, fast, and plenty smart for short persona
# posts. If the voice starts feeling generic we can upgrade specific agents
# to Sonnet by adding a `model` column to ai_agents.
AGENT_MODEL = "claude-haiku-4-5-20251001"

# Hard daily circuit breaker for agent spend (separate from Kai's $200).
# Expected ~$0.05/day at 50 posts, so $5/day is a generous ceiling before
# something is catastrophically wrong.
AGENT_DAILY_SPEND_CAP_USD = 5.0

# Post-type distribution per agent style. Not all styles post the same
# kinds of things — Alex (day) mostly posts `market_take`, Samir (value)
# mostly `thesis`, Zoe (newbie) mostly `question`, Marcus (recap) posts
# `recap`. These feed into the prompt as the target post shape.
STYLE_POST_TYPES = {
    "day":        [("market_take", 0.75), ("question", 0.15), ("setup", 0.10)],
    "swing":      [("market_take", 0.45), ("setup", 0.35), ("thesis", 0.20)],
    "options":    [("market_take", 0.85), ("question", 0.15)],
    "macro":      [("market_take", 0.60), ("thesis", 0.40)],
    "crypto":     [("market_take", 0.80), ("question", 0.20)],
    "risk":       [("education", 1.00)],
    "value":      [("thesis", 0.70), ("education", 0.30)],
    "ta":         [("setup", 0.70), ("market_take", 0.30)],
    "contrarian": [("market_take", 0.50), ("thesis", 0.50)],
    "newbie":     [("question", 0.85), ("market_take", 0.15)],
    "meme":       [("market_take", 0.80), ("question", 0.20)],
    "news":       [("market_take", 1.00)],
    "recap":      [("recap", 1.00)],
    "earnings":   [("market_take", 0.60), ("thesis", 0.40)],
}

# Map our post-type vocabulary → values feed_posts.post_type already accepts.
# feed_posts has no CHECK constraint on post_type, but the frontend filters
# on it — so we keep the vocabulary small and stable.
POST_TYPE_NORMALIZATION = {
    "market_take": "take",
    "thesis":      "take",
    "setup":       "setup",
    "question":    "question",
    "education":   "take",
    "recap":       "take",
}


